"""Remote Kompress: offload ML compression to a hosted ``/compress`` endpoint.

Lets a sandboxed proxy — installed WITHOUT the ``[ml]`` extra (no torch/onnx) —
still run Kompress by calling a remote endpoint over HTTP. The class mirrors
:class:`~headroom.transforms.kompress_compressor.KompressCompressor`'s public
surface (``is_ready`` / ``preload`` / ``ensure_background_load`` / ``compress``),
so it is a drop-in at the ContentRouter seam.

Only the model inference is remote. The CCR store + retrieval marker stay
proxy-local (the endpoint is stateless, ``enable_ccr=False``), so
``headroom_retrieve`` keeps working and original content never persists off-box.

Enabled by ``HEADROOM_KOMPRESS_ENDPOINT`` (+ optional
``HEADROOM_KOMPRESS_ENDPOINT_TOKEN``) — see ``ContentRouter._get_kompress``.
"""

from __future__ import annotations

import logging
import threading
import time

import httpx

from .kompress_compressor import KompressConfig, KompressResult, store_kompress_in_ccr

logger = logging.getLogger(__name__)

# Below this word count local Kompress passes through verbatim (KompressCompressor
# .compress); mirror it so we never pay a round-trip on a trivially small block.
_MIN_WORDS = 10

# Accept-any-shrink CCR gate, identical to KompressCompressor.compress: only
# store + mark when the shrink is worth the retrieval marker's own cost.
_CCR_RATIO_GATE = 0.8


class RemoteKompressCompressor:
    """Drop-in for KompressCompressor that POSTs to a hosted ``/compress`` endpoint.

    Fails OPEN: any network/HTTP error returns the content verbatim so a flaky
    endpoint degrades compression rather than breaking the proxy.
    """

    name = "kompress_compressor"
    # The content router keeps local Kompress lazy so a native model cannot
    # block proxy startup.  A remote broker is different: its cheap readiness
    # endpoint can be checked synchronously and represented in the warmup
    # registry without loading any local model.
    is_remote = True

    def __init__(
        self,
        endpoint: str,
        token: str | None = None,
        config: KompressConfig | None = None,
        timeout: float = 20.0,
    ) -> None:
        self.config = config or KompressConfig()
        endpoint = endpoint.rstrip("/")
        self._url = endpoint + "/compress"
        self._ready_url = endpoint + "/readyz"
        self._headers = {"content-type": "application/json"}
        if token:
            self._headers["authorization"] = f"Bearer {token}"
        # httpx.Client is safe to share across the proxy's worker threads.
        self._client = httpx.Client(timeout=timeout)
        # Keep readiness probes short even when compression itself has a more
        # generous budget.  A broker outage must never hold proxy startup.
        try:
            timeout_value = float(timeout)
        except (TypeError, ValueError):
            timeout_value = 3.0
        self._readiness_timeout = max(0.1, min(timeout_value, 3.0))
        self._ready = False
        self._provider: str | None = None
        self._backend: str | None = None
        self._preload_error: str | None = None
        self._reprobe_lock = threading.Lock()
        self._reprobe_thread: threading.Thread | None = None
        self._next_reprobe_at = 0.0
        self._reprobe_interval = 5.0

    # Nothing to load locally; short-circuit the router straight to compress().
    def is_ready(self) -> bool:
        return self._ready

    def preload(self, *, allow_download: bool = True) -> str:
        """Probe the broker readiness contract without sending request text.

        The broker's ``/readyz`` response is intentionally tiny and carries
        only ``ready``, ``provider`` and ``backend`` metadata.  Treat every
        transport, HTTP, JSON, or schema failure as non-ready so the caller
        can continue with the normal compression fail-open path.
        """

        del allow_download  # retained for KompressCompressor API parity
        self._ready = False
        self._provider = None
        self._backend = None
        self._preload_error = None
        try:
            response = self._client.get(
                self._ready_url,
                headers=self._headers,
                timeout=self._readiness_timeout,
            )
            response.raise_for_status()
            if getattr(response, "status_code", None) != 200:
                raise ValueError("broker_status_invalid")
            payload = response.json()
            if not isinstance(payload, dict) or payload.get("service") != "kompress-broker":
                raise ValueError("broker_service_invalid")
            if payload.get("ready") is not True:
                raise ValueError("broker_not_ready")
            if payload.get("status") != "healthy":
                raise ValueError("broker_status_invalid")
            provider = self._safe_metadata(payload.get("provider"))
            backend = self._safe_metadata(payload.get("backend"))
            if provider is None or backend is None:
                raise ValueError("broker_metadata_invalid")
        except httpx.TimeoutException:
            self._preload_error = "broker_timeout"
            return "unavailable"
        except httpx.HTTPStatusError:
            self._preload_error = "broker_http_error"
            return "unavailable"
        except httpx.HTTPError:
            self._preload_error = "broker_unreachable"
            return "unavailable"
        except (TypeError, ValueError, UnicodeError):
            self._preload_error = "broker_contract_error"
            return "unavailable"
        except Exception:
            # Never make startup depend on a third-party client's exception
            # hierarchy.  Do not include response bodies or exception text.
            self._preload_error = "broker_probe_error"
            return "unavailable"

        self._provider = provider
        self._backend = backend
        self._ready = True
        return "loaded"

    @staticmethod
    def _safe_metadata(value: object) -> str | None:
        if not isinstance(value, str):
            return None
        value = value.strip()
        if not value or len(value) > 80 or any(ord(char) < 0x20 for char in value):
            return None
        return value

    @property
    def provider(self) -> str | None:
        return self._provider

    @property
    def backend(self) -> str | None:
        return self._backend

    @property
    def preload_error(self) -> str | None:
        return self._preload_error

    def ensure_background_load(self) -> None:
        """Re-probe a recovered broker without blocking the request thread."""

        if self.is_ready():
            return
        now = time.monotonic()
        with self._reprobe_lock:
            if self._ready or now < self._next_reprobe_at:
                return
            if self._reprobe_thread is not None and self._reprobe_thread.is_alive():
                return
            self._next_reprobe_at = now + self._reprobe_interval
            thread = threading.Thread(
                target=self._background_preload,
                name="headroom-remote-kompress-ready",
                daemon=True,
            )
            self._reprobe_thread = thread
            thread.start()

    def _background_preload(self) -> None:
        try:
            self.preload(allow_download=False)
        finally:
            with self._reprobe_lock:
                if self._reprobe_thread is threading.current_thread():
                    self._reprobe_thread = None

    def _passthrough(self, content: str, n_words: int) -> KompressResult:
        return KompressResult(
            compressed=content,
            original=content,
            original_tokens=n_words,
            compressed_tokens=n_words,
            compression_ratio=1.0,
            model_used=self.config.model_id,
        )

    def compress(
        self,
        content: str,
        context: str = "",
        content_type: str | None = None,
        question: str | None = None,
        target_ratio: float | None = None,
        *,
        allow_download: bool = True,
    ) -> KompressResult:
        n_words = len(content.split())
        if n_words < _MIN_WORDS:
            return self._passthrough(content, n_words)

        try:
            resp = self._client.post(
                self._url,
                headers=self._headers,
                json={"content": content, "target_ratio": target_ratio},
            )
            resp.raise_for_status()
            data = resp.json()
            compressed = data["compressed"]
            if not isinstance(compressed, str):
                raise TypeError("remote Kompress response field 'compressed' must be a string")
        except Exception as e:  # fail OPEN — never break the proxy on a bad endpoint
            # A failed request invalidates this worker-local snapshot.  The
            # independent broker monitor remains the source of truth for
            # subsequent recovery; compression itself still passes through.
            self._ready = False
            self._provider = None
            self._backend = None
            self._preload_error = "broker_request_error"
            with self._reprobe_lock:
                self._next_reprobe_at = 0.0
            # Log only the exception class; a third-party exception message
            # could contain a response fragment or request-derived text.
            logger.warning(
                "Remote Kompress failed (%s); passing through",
                type(e).__name__,
            )
            return self._passthrough(content, n_words)

        result = KompressResult(
            compressed=compressed,
            original=content,
            original_tokens=int(data.get("original_tokens", n_words)),
            compressed_tokens=int(data.get("compressed_tokens", len(compressed.split()))),
            compression_ratio=float(data.get("compression_ratio", 1.0)),
            model_used=str(data.get("model_used", self.config.model_id)),
        )

        # CCR stays PROXY-LOCAL: endpoint is stateless (enable_ccr=False), so we
        # store the mapping + append the retrieval marker here — same policy and
        # marker format as KompressCompressor.compress.
        if self.config.enable_ccr and result.compression_ratio < _CCR_RATIO_GATE:
            cache_key = store_kompress_in_ccr(content, compressed, result.original_tokens)
            if cache_key:
                result.cache_key = cache_key
                result.compressed += (
                    f"\n[{result.original_tokens} items compressed to "
                    f"{result.compressed_tokens}. Retrieve more: hash={cache_key}]"
                )

        return result

    def close(self) -> None:
        self._client.close()
